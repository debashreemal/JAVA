public class Convert {
    public static void main(String[] args){

        double distkm = 6.7;
        double distm = distkm * 1000;
        double distcm = distkm * 100000;

        System.out.println("Distance km = " + distkm);
        System.out.println("Distance m = " + distm);
        System.out.println("Distance cm = " + distcm);
    }
}
