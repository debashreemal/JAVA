public class Agecompare {
    public static void main(String[] args){
        int age1 = 18;
        int age2 = 25;

        if(age1>age2){
            System.out.println("Age1 is greater than Age2");
        }
        else if(age1<age2){
            System.out.println("Age1 is smaller than Age2");
        }
        else{
            System.out.println("Both ages are equal");
        }
    }
}
