// Positive , negative or zero 

public class integer {
    public static void main(String[] args) {
        int a = 0;

        if( a < 0 ){
            System.out.println("Negative Number");
        }
        else if ( a > 0 ){
            System.out.println("Positive Number");
        }
        else{
            System.out.println("Number is Zero");
        }
    }
}
